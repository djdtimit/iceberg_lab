"""docs/rest-conformance.md from the last results of tests/catalog/test_rest_conformance.py (all catalogs).

uv run python scripts/rest_conformance_doc.py
"""

from __future__ import annotations

import gzip
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
#: Comparison rows of the latest full run per catalog (scripts/export_reference.py).
SOURCES = {
    cat: ROOT / "results" / f"{name}.rows.json.gz"
    for cat, name in (
        ("Lakekeeper", "lakekeeper"),
        ("Polaris", "polaris"),
        ("RustFS", "rustfs"),
        ("Unity", "unity"),
        ("Reference", "reference"),
    )
}
SYMBOL = {"pass": "✅", "gap": "❌", "new": "⚠️", "fixed": "🔧", "na": "—", "blocked": "·"}


def main() -> None:
    """Write docs/rest-conformance.md from the five catalogs' results."""
    cells: dict[str, dict[str, tuple[str, str]]] = {}
    for cat, path in SOURCES.items():
        for r in json.loads(gzip.decompress(path.read_bytes())):
            file, _, rest = r["test"].partition("::")
            if not file.endswith("/test_rest_conformance.py"):
                continue
            func = rest.split("[")[0]
            m = re.search(r"\[(.*)\]$", rest)
            row = f"{func.removeprefix('test_')}: {m[1]}" if m else func.removeprefix("test_")
            cells.setdefault(row, {})[cat] = (r["status"], r["detail"])
    lines = [
        "# REST conformance of the catalogs",
        "",
        "Generated by `scripts/rest_conformance_doc.py` from the last results of",
        "`tests/catalog/test_rest_conformance.py`; nothing here is entered by hand.",
        "",
        "- **spec_endpoint**: every endpoint of the Iceberg REST specification gets a valid",
        "  request. ✅ works (and is advertised in `/v1/config` if the catalog keeps a list);",
        "  — not offered (404/405/406/501 without a domain error type, not advertised);",
        "  ❌ known gap; ⚠️ new failure.",
        "- Other rows: behaviour the specification defines (error document, HEAD 204, missing",
        "  parent, `snapshots=refs`/invalid value, missing metadata file).",
        "",
        "| Check | " + " | ".join(SOURCES) + " |",
        "|---|" + "---|" * len(SOURCES),
    ]
    notes = []
    for row in sorted(cells, key=lambda x: (not x.startswith("spec_endpoint"), x)):
        out = []
        for cat in SOURCES:
            status, detail = cells[row].get(cat, ("", ""))
            out.append(SYMBOL.get(status, "?"))
            if status in ("gap", "new"):
                notes.append(f"- **{cat}, {row}**: {detail}")
        lines.append(f"| `{row}` | " + " | ".join(out) + " |")
    if notes:
        lines += ["", "## Deviations", "", *notes]
    (ROOT / "docs/rest-conformance.md").write_text("\n".join(lines) + "\n")
    print(f"{len(cells)} rows")


if __name__ == "__main__":
    main()
