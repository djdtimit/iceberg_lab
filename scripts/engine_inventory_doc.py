"""docs/engine-inventory.md: what each engine offers (live baselines of tests/selftest/test_engine_inventory.py)
and how its base tests went on all catalogs (last results). Nothing is entered by hand.

    uv run python scripts/engine_inventory_doc.py
"""

from __future__ import annotations

import gzip
import json
import pathlib
import sys
from collections import Counter, defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "tests"), str(ROOT / "tests" / "lab")]
from iceberg_lab.lab.reporting import DIMENSIONS, ENGINE_ORDER, NOT_COMPARED

#: Comparison rows of the latest full run per catalog (scripts/export_reference.py).
SOURCES = {
    name: ROOT / "results" / f"{name}.rows.json.gz"
    for name in (
        "lakekeeper",
        "polaris",
        "rustfs",
        "unity",
        "reference",
        "gravitino",
        "gravitino_lakekeeper",
        "gravitino_polaris",
        "gravitino_unity",
        "gravitino_rustfs",
    )
}


def main() -> None:
    """Write docs/engine-inventory.md from the recorded engine inventories and the results."""
    lines = [
        "# Engine inventory",
        "",
        "Generated by `scripts/engine_inventory_doc.py`; nothing here is entered by hand.",
        "",
        "## What each engine offers for Iceberg",
        "",
        "Read live from the engine (`tests/selftest/test_engine_inventory.py`, baselines in",
        "`docs/api/engine-<engine>.txt`). If a new version changes the list, the test fails until",
        "the change is classified.",
        "",
        "| Engine | Count | Source | Entries |",
        "|---|---|---|---|",
    ]
    source = {
        "pyiceberg": "public methods (Catalog, Table, Transaction, Inspect, Snapshots, Schema, Spec)",
        "duckdb": "duckdb_functions()",
        "polars": 'functions/methods containing "iceberg"',
        "daft": 'functions/methods containing "iceberg"',
        "spark": "Iceberg procedures (CALL)",
        "trino": "functions, procedures, table properties",
        "pg_lake": "functions of the pg_lake schemas",
        "flink": "procedures of the Iceberg catalog",
    }
    for engine in ENGINE_ORDER:
        path = ROOT / "docs" / "api" / f"engine-{engine}.txt"
        entries = [e for e in path.read_text().split("\n") if e] if path.exists() else []
        shown = ", ".join(f"`{e.split(':', 1)[-1]}`" for e in entries[:40])
        more = f" … (+{len(entries) - 40})" if len(entries) > 40 else ""
        lines.append(f"| {engine} | {len(entries)} | {source[engine]} | {shown}{more} |")

    cells: dict[tuple[str, str], Counter] = defaultdict(Counter)
    for path in SOURCES.values():
        for row in json.loads(gzip.decompress(path.read_bytes())):
            if row["area"] in NOT_COMPARED or row["engine"] not in ENGINE_ORDER:
                continue
            cells[(row["area"], row["engine"])][row["status"]] += 1
    areas = [name for name, _ in DIMENSIONS if name not in NOT_COMPARED]
    lines += [
        "",
        "## How the base tests went per engine (all catalogs together)",
        "",
        "Per cell: passed / checked (checked = passed + known gap + new failure);",
        '"—" not offered or not testable. Details and reasons: dashboard and `results/`.',
        "",
        "| Area | " + " | ".join(ENGINE_ORDER) + " |",
        "|---|" + "---|" * len(ENGINE_ORDER),
    ]
    for area in areas:
        row = []
        for engine in ENGINE_ORDER:
            c = cells.get((area, engine))
            tested = (c["pass"] + c["gap"] + c["new"]) if c else 0
            row.append(f"{c['pass']}/{tested}" if tested else "—")
        if any(x != "—" for x in row):
            lines.append(f"| {area} | " + " | ".join(row) + " |")
    (ROOT / "docs/engine-inventory.md").write_text("\n".join(lines) + "\n")
    print(f"{len(areas)} areas")


if __name__ == "__main__":
    main()
